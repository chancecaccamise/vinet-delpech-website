/**
 * Outlines for the home page's locator map, in longitude and latitude.
 *
 * Source: the france-geojson dataset (gregoiredavid), itself derived from the
 * IGN's open boundaries — `departements-version-simplifiee.geojson` for the
 * departments, `metropole-version-simplifiee.geojson` for the country. Thinned
 * again here with Douglas–Peucker (about 2 km for the departments and the land
 * around them, about 12 km for the country thumbnail): the map is meant to
 * read as a drawing, not as a survey.
 *
 * Two decisions in that thinning are deliberate:
 *
 * - Charente-Maritime and Charente share 56 vertices in the source. Thinning
 *   each ring on its own pulls that shared line apart, so the border was cut
 *   out, thinned once, and spliced back into both. Both shapes carry the same
 *   line, which is what keeps the white channel between them even.
 * - The land around the pair is built from the *other departments* in the same
 *   file rather than from the country outline. Neighbours share their vertices
 *   exactly, so no seam can open along the coast between the land and the
 *   region drawn on top of it. The rings are clipped to a window a little
 *   wider than the map's own, which is why some of them end on straight lines.
 *
 * Coordinates carry four decimal places, about 10 m — far finer than this
 * drawing resolves.
 */

export type Point = readonly [number, number];
export type Ring = readonly Point[];

/** "lon lat, lon lat, …" — the data reads as coordinates rather than as code. */
const ring = (source: string): Ring =>
  source
    .trim()
    .split(",")
    .map((pair) => {
      const [lon, lat] = pair.trim().split(/\s+/).map(Number);
      return [lon, lat] as const;
    });

